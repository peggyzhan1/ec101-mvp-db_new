@dataclass(frozen=True)
class Issue:
    code: str
    sheet: str
    row: int | None
    column: str | None
    message: str


def validate_rows(sheet: str, rows: list[dict[str, Any]]) -> list[Issue]:
    """Validate one standard sheet without cross-sheet or database rules."""
    if sheet not in SHEET_COLUMNS:
        return [Issue("unknown_sheet", sheet, None, None, "不支持的工作表")]
    columns = set(SHEET_COLUMNS[sheet])
    issues: list[Issue] = []
    for row_number, row in enumerate(rows, start=2):
        for column in row:
            if column not in columns:
                issues.append(Issue("unknown_column", sheet, row_number, column, "不支持的字段"))
        for column in REQUIRED_COLUMNS.get(sheet, ()):
            value = row.get(column)
            if value is None or str(value).strip() == "":
                issues.append(Issue("required", sheet, row_number, column, "必填字段为空"))
    return issues
